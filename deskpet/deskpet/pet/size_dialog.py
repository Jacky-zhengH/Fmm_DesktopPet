"""An explicit size control, with live preview and cancel-to-restore semantics."""
from PySide6.QtCore import Qt, Signal
from PySide6.QtWidgets import (QDialog, QDialogButtonBox, QHBoxLayout, QLabel,
                               QPushButton, QSlider, QVBoxLayout)
from pet.settings import MAX_SIZE, MIN_SIZE


class SizeDialog(QDialog):
    preview_size = Signal(int)

    def __init__(self, size, parent=None):
        super().__init__(parent)
        self.setWindowFlags(Qt.Dialog | Qt.WindowStaysOnTopHint)
        self.setWindowTitle("调整芙眠眠的大小")
        self.setMinimumWidth(360)
        self.setModal(True)
        layout = QVBoxLayout(self)
        layout.setContentsMargins(24, 20, 24, 20)
        layout.setSpacing(16)
        heading = QLabel("选择舒服的显示大小")
        heading.setStyleSheet("font-size: 17px; font-weight: 600;")
        layout.addWidget(heading)
        self.value_label = QLabel()
        self.value_label.setAlignment(Qt.AlignCenter)
        self.value_label.setStyleSheet("font-size: 26px; font-weight: 600;")
        layout.addWidget(self.value_label)
        row = QHBoxLayout()
        self.smaller = QPushButton("−")
        self.smaller.setAccessibleName("缩小 10%")
        self.smaller.setFixedWidth(44)
        self.larger = QPushButton("＋")
        self.larger.setAccessibleName("放大 10%")
        self.larger.setFixedWidth(44)
        self.slider = QSlider(Qt.Horizontal)
        self.slider.setAccessibleName("大小百分比")
        self.slider.setRange(MIN_SIZE // 2, MAX_SIZE // 2)
        self.slider.setSingleStep(10)
        self.slider.setPageStep(10)
        row.addWidget(self.smaller)
        row.addWidget(self.slider, 1)
        row.addWidget(self.larger)
        layout.addLayout(row)
        limits = QLabel(f"最小 {MIN_SIZE // 2}%                       最大 {MAX_SIZE // 2}%")
        layout.addWidget(limits)
        note = QLabel("拖动滑条可实时预览。普通滚轮不会改变大小。\n快捷操作：按住 Ctrl，再在芙眠眠上滚动滚轮。")
        note.setWordWrap(True)
        layout.addWidget(note)
        self.reset_button = QPushButton("恢复默认 100%")
        self.reset_button.clicked.connect(lambda: self.slider.setValue(100))
        layout.addWidget(self.reset_button)
        self.buttons = QDialogButtonBox(QDialogButtonBox.Ok | QDialogButtonBox.Cancel)
        self.buttons.button(QDialogButtonBox.Ok).setText("确定")
        self.buttons.button(QDialogButtonBox.Cancel).setText("取消")
        self.buttons.button(QDialogButtonBox.Ok).setDefault(True)
        self.buttons.accepted.connect(self.accept)
        self.buttons.rejected.connect(self.reject)
        layout.addWidget(self.buttons)
        self.smaller.clicked.connect(lambda: self.slider.setValue(self.slider.value() - 10))
        self.larger.clicked.connect(lambda: self.slider.setValue(self.slider.value() + 10))
        self.slider.valueChanged.connect(self._preview)
        self.slider.setValue(max(MIN_SIZE, min(MAX_SIZE, int(size))) // 2)
        self._preview(self.slider.value())

    def _preview(self, percentage):
        self.value_label.setText(f"{percentage}%")
        self.smaller.setEnabled(percentage > self.slider.minimum())
        self.larger.setEnabled(percentage < self.slider.maximum())
        self.preview_size.emit(percentage * 2)
